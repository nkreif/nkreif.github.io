"""Regenerate data/publications.json from the CV repository, so the website and the CV
share one list of publications.

    python scripts/sync_from_cv.py [path/to/cv]     # default: ../cv
    python scripts/build.py

Facts (authors, journal, year, volume, pages, DOI, status) come from cv/data/publications.yaml.
Research themes come from cv/data/themes.yaml and each entry's topics. Website-only details
(sentence-case titles, selection for the home page, research-page tags, plain-language takeaways, preprint/code/software links) come from data/site.json.
Trainee names come from cv/data/trainees.yaml. Do not edit data/publications.json by hand.
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CV = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "cv"

TYPE = {"article": "article", "chapter": "chapter", "working": "working", "submitted": "working"}


def venue(p):
    """Journal, volume(issue), pages -- in the style the site has always used."""
    if p["type"] == "submitted":
        return f"Submitted to {p['venue']}"
    if p["type"] == "working":
        return p["venue"]
    name = p.get("journal") or p.get("venue", "")
    if p["type"] == "chapter" and not p.get("volume"):
        return name[4:] if name.startswith("In: ") else name
    parts = [name]
    if p.get("volume"):
        parts.append(f"{p['volume']}" + (f"({p['issue']})" if p.get("issue") else ""))
    if p.get("pages") and p.get("status", "published") != "online":
        parts.append(str(p["pages"]).replace("-", "–"))
    return ", ".join(parts)


NOTE = {"accepted": "accepted", "inpress": "in press", "online": "online ahead of print"}


def main():
    cv = yaml.safe_load((CV / "data/publications.yaml").read_text(encoding="utf-8"))["publications"]
    trainees = yaml.safe_load((CV / "data/trainees.yaml").read_text(encoding="utf-8"))["trainees"]
    themes = yaml.safe_load((CV / "data/themes.yaml").read_text(encoding="utf-8"))["themes"]
    site = json.loads((ROOT / "data/site.json").read_text(encoding="utf-8"))
    entries = site["entries"]

    out, missing = [], []
    for p in cv:
        if p["type"] not in TYPE or not p.get("include", True):
            continue
        e = entries.get(p["id"])
        if e is None:
            missing.append(p["id"])
            e = {}
        if e.get("hide"):
            continue
        rec = {
            "id": p["id"],
            "year": p.get("year") or (max(int(x.get("year") or 0) for x in cv) or ""),
            "type": TYPE[p["type"]],
            "title": e.get("title") or p["title"],
            "authors": p["authors"],
            "venue": venue(p),
        }
        url = e.get("url") or (f"https://doi.org/{p['doi']}" if p.get("doi") else p.get("url"))
        if url:
            rec["url"] = url
        note = NOTE.get(p.get("status"))
        if note:
            rec["note"] = note
        if p.get("topics"):
            rec["topics"] = p["topics"]
        for k in ("selected", "tags", "takeaway", "links"):
            if e.get(k):
                rec[k] = e[k]
        out.append(rec)

    data = {
        "_readme": "GENERATED by scripts/sync_from_cv.py from the CV repository and data/site.json. Do not edit by hand.",
        "topics": themes,
        "trainees": trainees,
        "publications": out,
    }
    (ROOT / "data/publications.json").write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n",
                                                 encoding="utf-8", newline="\n")
    print(f"Wrote data/publications.json ({len(out)} publications)")
    if missing:
        print("New in the CV, not yet in data/site.json (shown with the CV title):")
        for m in missing:
            print("  -", m)


if __name__ == "__main__":
    main()
